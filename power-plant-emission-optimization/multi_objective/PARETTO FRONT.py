# PROBLEM SETUP

# Bounds (physical units)
lb = np.array([65,  1,  0,  695000, 225, 815], dtype=float)
ub = np.array([95,  5,  4,  725000, 245, 855], dtype=float)

VAR_NAMES = [
    'x1: SH spray flow (t/h)',
    'x2: RH spray flow (t/h)',
    'x3: APH leakage (%)',
    'x4: Boiler energy (Mcal/h)',
    'x5: Feedwater temp (F)',
    'x6: Feedwater flow (t/h)',
]

def normalize(x):
    return (x - lb) / (ub - lb)

def unnormalize(x_norm):
    return lb + x_norm * (ub - lb)


# ALL REGRESSION MODELS

# Emissions
c_SO2  = np.array([0.078097, -0.022689,  0.055804, 0.0,  0.203204, 0.222676])
c_NOx  = np.array([0.019987, -0.222401,  0.116002, 0.0,  0.046811, 0.099485])
c_CO   = np.array([-0.130366, 0.557775, -0.448537, 0.0,  0.244969, 0.104185])
c_CO2  = np.array([9.657000, 10.239256,  6.363121, 6.4e-5, 39.745566, 50.958021])
c_Dust = np.array([-0.004186, -0.005248, -0.015129, 0.0,  0.003998, 0.004433])

AVG_SO2, AVG_NOx, AVG_CO, AVG_CO2, AVG_Dust = 437.50, 194.16, 260.93, 95367.0, 4.27
w_SO2, w_NOx, w_CO, w_CO2, w_Dust = 0.25, 0.25, 0.25, 0.15, 0.10

# Heat rates and efficiency
c_NPHR = np.array([0.2598, 0.3361, 0.2394, 0.001727, 1.1498, 1.4238])
c_NTHR = np.array([0.2379, 0.2909, 0.3460, 0.0000, 1.0487, 1.3266])  # g1
c_HHV  = np.array([0.3817, 0.3432, 0.2709, 0.0000, 1.7837, 2.2291])  # g2

# Power output
c_GrossLoad = np.array([0.0281, 0.0269, 0.0278, 0.0000, 0.1242, 0.1534])  # g3
c_NetLoad   = np.array([0.0282, 0.0101, 0.0246, 0.0000, 0.1141, 0.1447])  # g4

# OBJECTIVE FUNCTIONS

def J1_emissions(x):
    """Objective 1: Total weighted normalized emissions"""
    SO2_norm  = (c_SO2  @ x) / AVG_SO2
    NOx_norm  = (c_NOx  @ x) / AVG_NOx
    CO_norm   = (c_CO   @ x) / AVG_CO
    CO2_norm  = (c_CO2  @ x) / AVG_CO2
    Dust_norm = (c_Dust @ x) / AVG_Dust
    return w_SO2*SO2_norm + w_NOx*NOx_norm + w_CO*CO_norm + w_CO2*CO2_norm + w_Dust*Dust_norm

def J2_nphr(x):
    """Objective 2: Net Plant Heat Rate (lower is better)"""
    return c_NPHR @ x

def calc_all_outputs(x):
    """Calculate all outputs for a given design x"""
    return {
        'Emissions': J1_emissions(x),
        'NPHR': J2_nphr(x),
        'SO2': c_SO2 @ x,
        'NOx': c_NOx @ x,
        'CO': c_CO @ x,
        'CO2': c_CO2 @ x,
        'Dust': c_Dust @ x,
        'NTHR': c_NTHR @ x,
        'HHV': c_HHV @ x,
        'Gross_Load': c_GrossLoad @ x,
        'Net_Load': c_NetLoad @ x,
    }

# NORMAL BOUNDARY INTERSECTION (NBI) METHOD

def find_anchor_points():
    """Find individual optima (anchor points) for both objectives"""

    def solve_single_objective(objective_func):
        """Minimize a single objective"""
        bounds = [(0, 1) for _ in range(6)]
        x0_norm = 0.5 * np.ones(6)

        result = minimize(
            fun=lambda x: objective_func(unnormalize(x)),
            x0=x0_norm,
            method='SLSQP',
            bounds=bounds,
            options={'maxiter': 500, 'ftol': 1e-8, 'disp': False}
        )

        if result.success:
            return unnormalize(result.x)
        return None

    # Find anchor points
    x1_star = solve_single_objective(J1_emissions)  # Min emissions
    x2_star = solve_single_objective(J2_nphr)       # Min NPHR

    out1 = calc_all_outputs(x1_star)
    out2 = calc_all_outputs(x2_star)

    return x1_star, x2_star, out1, out2

def solve_nbi_subproblem(beta, anchor1_shifted, anchor2_shifted, J_utopia):
    """
    Solve single NBI subproblem for parameter beta ∈ [0,1]

    NBI formulation:
      Maximize: t  (distance along normal to CHIM)
      Subject to: J(x) = point_on_CHIM - t*normal

    Args:
        beta: Parameter in [0,1] defining point on CHIM
        anchor1_shifted: First anchor in shifted coordinates
        anchor2_shifted: Second anchor in shifted coordinates
        J_utopia: Utopia point for coordinate shift
    """

    # Point on CHIM (Convex Hull of Individual Minima)
    chim_point = beta * anchor1_shifted + (1 - beta) * anchor2_shifted

    # Normal vector to CHIM (perpendicular to line connecting anchors)
    chim_direction = anchor2_shifted - anchor1_shifted
    normal = np.array([-chim_direction[1], chim_direction[0]])
    normal = normal / np.linalg.norm(normal)  # Normalize

    # Optimization variables: [x1, x2, x3, x4, x5, x6, t]
    def objective_nbi(vars):
        """Minimize -t (equivalent to maximizing t)"""
        return -vars[6]

    def equality_constraint(vars):
        """Constraint: J(x) = chim_point - t*normal"""
        x_norm = vars[:6]
        t = vars[6]

        x_phys = unnormalize(x_norm)
        J1_val = J1_emissions(x_phys)
        J2_val = J2_nphr(x_phys)

        # Shift to utopia origin
        J_shifted = np.array([J1_val - J_utopia[0], J2_val - J_utopia[1]])

        # Should equal: chim_point - t*normal
        target = chim_point - t * normal

        return J_shifted - target  # Should be zero vector

    # Initial guess
    x0_norm = 0.5 * np.ones(6)
    t0 = 0.0
    vars0 = np.concatenate([x0_norm, [t0]])

    # Bounds
    bounds = [(0, 1) for _ in range(6)] + [(-10, 10)]  # x in [0,1], t unbounded

    # Solve
    result = minimize(
        fun=objective_nbi,
        x0=vars0,
        method='SLSQP',
        bounds=bounds,
        constraints={'type': 'eq', 'fun': equality_constraint},
        options={'maxiter': 1000, 'ftol': 1e-9, 'disp': False}
    )

    if result.success:
        x_opt = unnormalize(result.x[:6])
        t_opt = result.x[6]
        outputs = calc_all_outputs(x_opt)
        outputs['t'] = t_opt
        outputs['beta'] = beta
        outputs['x'] = x_opt
        return outputs

    return None


