"""
Bi-Objective Optimization: Emissions vs. NPHR
Using Normal Boundary Intersection (NBI) Method

OBJECTIVES:
  J1 = Total Emissions (SO2, NOx, CO, CO2, Dust - weighted normalized sum)
  J2 = NPHR (Net Plant Heat Rate - efficiency in kcal/kWh)

METHOD:
  Normal Boundary Intersection (NBI)
  - Generates evenly-distributed Pareto points
  - Better coverage than weighted sum
  - Handles non-convex regions

ADDITIONAL OUTPUTS (reported but not optimized):
  - NTHR, HHV, Gross Load, Net Load
  - Individual emissions: SO2, NOx, CO, CO2, Dust
"""

